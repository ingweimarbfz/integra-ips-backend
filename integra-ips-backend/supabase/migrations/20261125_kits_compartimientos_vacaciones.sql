-- IIPS-036 · Compartimientos de kits/ambulancias, áreas de correspondencia con personas y solicitudes de vacaciones.
alter table public.warehouses add column if not exists compartments jsonb not null default '[]';
alter table public.warehouses add column if not exists responsible_user_id bigint references public.users(id) on delete set null;
alter table public.kit_contents add column if not exists compartment text;

create table if not exists public.corr_area_members (
  org_id bigint not null default current_org_id(),
  area_id bigint not null references public.corr_areas(id) on delete cascade,
  user_id bigint not null references public.users(id) on delete cascade,
  primary key (area_id, user_id)
);
alter table public.corr_area_members enable row level security;

create table if not exists public.th_vacation_requests (
  id bigint generated by default as identity primary key,
  org_id bigint not null default current_org_id(),
  staff_id bigint not null references public.th_staff(id) on delete cascade,
  start_date date not null,
  end_date date not null,
  business_days numeric not null check (business_days > 0),
  status text not null default 'pendiente' check (status in ('pendiente', 'aprobada', 'rechazada', 'reprogramada', 'cancelada')),
  notes text,
  response_note text,
  requested_by bigint references public.users(id),
  decided_by bigint references public.users(id),
  decided_at timestamptz,
  vacation_id bigint references public.th_vacations(id) on delete set null,
  created_at timestamptz not null default now()
);
create index if not exists th_vacation_requests_staff_idx on public.th_vacation_requests (staff_id, status);
alter table public.th_vacation_requests enable row level security;
