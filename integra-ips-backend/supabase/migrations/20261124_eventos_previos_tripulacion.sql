-- IIPS-025 · Eventos previos (programación y cotización al cliente) y tripulación de vehículos/traslados.

-- 1) Eventos programados: servicios, actividades de educación y traslados que un cliente contrata con anticipación.
create table if not exists public.planned_events (
  id bigint generated by default as identity primary key,
  org_id bigint not null default current_org_id(),
  code text,
  area text not null check (area in ('socorro', 'educacion', 'traslado')),
  status text not null default 'borrador' check (status in ('borrador', 'cotizado', 'aprobado', 'ejecutado', 'cancelado')),
  name text not null,
  description text,
  place text,
  site_id bigint references public.sites(id),
  starts_at timestamptz,
  ends_at timestamptz,
  attendees integer,                 -- personas que se atienden o asisten
  client_name text, client_nit text, client_contact text, client_phone text, client_email text,
  coordinator_volunteer_id bigint references public.volunteers(id) on delete set null,
  needs_driver boolean not null default false,
  vehicles jsonb not null default '[]',        -- [{ type: 'TAB'|'TAM'|'otro', quantity }]
  personnel jsonb not null default '[]',       -- [{ role, agrupacion?, quantity }]
  elements jsonb not null default '[]',        -- [{ productId?, kitId?, name, quantity }]
  price_items jsonb not null default '[]',     -- [{ concept, quantity, unitPrice }]
  notes text,
  valid_until date,
  event_id bigint references public.gso_events(id) on delete set null,
  trip_id bigint references public.vehicle_trips(id) on delete set null,
  created_by bigint references public.users(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (org_id, code)
);
create index if not exists planned_events_org_idx on public.planned_events (org_id, starts_at);
alter table public.planned_events enable row level security;

-- 2) Tripulación del reporte de vehículo o traslado: auxiliar de traslado y médico (usuarios registrados).
create table if not exists public.vehicle_trip_crew (
  id bigint generated by default as identity primary key,
  org_id bigint not null default current_org_id(),
  trip_id bigint not null references public.vehicle_trips(id) on delete cascade,
  user_id bigint not null references public.users(id),
  role text not null check (role in ('auxiliar', 'medico')),
  created_at timestamptz not null default now(),
  unique (trip_id, user_id)
);
create index if not exists vehicle_trip_crew_trip_idx on public.vehicle_trip_crew (trip_id);
alter table public.vehicle_trip_crew enable row level security;
