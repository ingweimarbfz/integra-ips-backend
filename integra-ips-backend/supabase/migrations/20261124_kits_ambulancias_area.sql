-- IIPS-024 · Inventario por área, kits/botiquines, dotación de ambulancias y elementos por unidad en eventos.
-- Todo es aditivo: las bodegas existentes quedan como kind = 'bodega'.

-- 1) Kits, botiquines y ambulancias son "bodegas" de la sede con su propio stock.
alter table public.warehouses add column if not exists kind text not null default 'bodega'
  check (kind in ('bodega', 'kit', 'botiquin', 'ambulancia'));
alter table public.warehouses add column if not exists vehicle_id bigint references public.vehicles(id) on delete set null;
create unique index if not exists warehouses_vehicle_uidx on public.warehouses (vehicle_id) where vehicle_id is not null;

-- 2) Dotación estándar de cada kit, botiquín o ambulancia (lo que debe tener).
create table if not exists public.kit_contents (
  id bigint generated by default as identity primary key,
  org_id bigint not null default current_org_id(),
  warehouse_id bigint not null references public.warehouses(id) on delete cascade,
  product_id bigint not null references public.inventory_products(id) on delete cascade,
  quantity numeric not null check (quantity > 0),
  created_at timestamptz not null default now(),
  unique (warehouse_id, product_id)
);
create index if not exists kit_contents_org_idx on public.kit_contents (org_id);
alter table public.kit_contents enable row level security;

-- 3) Consumo de insumos en reportes de vehículo y traslados (dotación de la ambulancia).
alter table public.inventory_movements add column if not exists trip_id bigint references public.vehicle_trips(id) on delete set null;
create table if not exists public.vehicle_trip_supplies (
  id bigint generated by default as identity primary key,
  org_id bigint not null default current_org_id(),
  trip_id bigint not null references public.vehicle_trips(id) on delete cascade,
  item_id bigint not null references public.inventory_items(id),
  quantity numeric not null check (quantity > 0),
  observation text,
  created_by bigint references public.users(id),
  created_at timestamptz not null default now()
);
create index if not exists vehicle_trip_supplies_trip_idx on public.vehicle_trip_supplies (trip_id);
alter table public.vehicle_trip_supplies enable row level security;

-- 4) Estado por unidad de un material al regresar del evento (p. ej. cuál de las 2 camillas volvió mala).
create table if not exists public.gso_event_material_units (
  id bigint generated by default as identity primary key,
  org_id bigint not null default current_org_id(),
  material_id bigint not null references public.gso_event_materials(id) on delete cascade,
  unit_label text not null,
  state text not null default 'bueno' check (state in ('bueno', 'regular', 'malo', 'perdido')),
  observation text,
  created_at timestamptz not null default now()
);
create index if not exists gso_event_material_units_mat_idx on public.gso_event_material_units (material_id);
alter table public.gso_event_material_units enable row level security;
