-- IIPS-023 · Directores de área: revisan y firman los reportes de su área en lugar del administrador.
-- area: socorro_operaciones | talento_humano | ips | educacion. En IPS, service_id = null es el director general
-- y un service_id es el director de ese servicio ofertado.
create table if not exists public.area_directors (
  id bigint generated by default as identity primary key,
  org_id bigint not null default current_org_id(),
  area text not null check (area in ('socorro_operaciones', 'talento_humano', 'ips', 'educacion')),
  service_id bigint references public.ips_services(id) on delete cascade,
  user_id bigint not null references public.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  unique nulls not distinct (org_id, area, service_id)
);
create index if not exists area_directors_user_idx on public.area_directors (user_id);
alter table public.area_directors enable row level security;
