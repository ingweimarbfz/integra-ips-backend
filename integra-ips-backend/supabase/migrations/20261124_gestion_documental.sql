-- IIPS-030 · Gestión documental y correspondencia (ventanilla única).

-- Áreas o dependencias que reciben correspondencia, con su prefijo y consecutivo anual.
create table if not exists public.corr_areas (
  id bigint generated by default as identity primary key,
  org_id bigint not null default current_org_id(),
  name text not null,
  prefix text not null,
  manager_user_id bigint references public.users(id) on delete set null,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  unique (org_id, prefix)
);
alter table public.corr_areas enable row level security;
create table if not exists public.corr_counters (
  org_id bigint not null default current_org_id(),
  area_id bigint not null references public.corr_areas(id) on delete cascade,
  direction text not null,
  year integer not null,
  last integer not null default 0,
  primary key (org_id, area_id, direction, year)
);
alter table public.corr_counters enable row level security;

-- Consecutivo atómico por área, sentido y año.
create or replace function public.corr_next(p_area bigint, p_direction text, p_year integer) returns integer
language plpgsql as $$
declare n integer;
begin
  insert into public.corr_counters (org_id, area_id, direction, year, last) values (current_org_id(), p_area, p_direction, p_year, 1)
  on conflict (org_id, area_id, direction, year) do update set last = public.corr_counters.last + 1
  returning last into n;
  return n;
end $$;

create table if not exists public.correspondence (
  id bigint generated by default as identity primary key,
  org_id bigint not null default current_org_id(),
  code text not null,
  direction text not null default 'entrada' check (direction in ('entrada', 'salida', 'interna')),
  kind text not null default 'documento',
  subject text not null,
  description text,
  sender_name text, sender_org text, sender_doc text, sender_contact text, sender_address text,
  carrier text, tracking_number text, folios integer, attachments_desc text,
  received_at timestamptz not null default now(),
  area_id bigint references public.corr_areas(id),
  recipient_user_id bigint references public.users(id),
  site_id bigint references public.sites(id),
  priority text not null default 'normal' check (priority in ('normal', 'urgente')),
  requires_response boolean not null default false,
  due_date date,
  status text not null default 'radicado' check (status in ('radicado', 'entregado', 'en_revision', 'respondido', 'archivado', 'devuelto', 'anulado')),
  parent_id bigint references public.correspondence(id) on delete set null,
  delivered_at timestamptz, delivered_to text, delivery_signature_url text,
  closed_at timestamptz,
  created_by bigint references public.users(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (org_id, code)
);
create index if not exists correspondence_recipient_idx on public.correspondence (recipient_user_id, status);
create index if not exists correspondence_area_idx on public.correspondence (area_id, status);
alter table public.correspondence enable row level security;

create table if not exists public.corr_files (
  id bigint generated by default as identity primary key,
  org_id bigint not null default current_org_id(),
  corr_id bigint not null references public.correspondence(id) on delete cascade,
  url text not null, name text, mime text, kind text not null default 'soporte',
  created_by bigint references public.users(id),
  created_at timestamptz not null default now()
);
alter table public.corr_files enable row level security;

create table if not exists public.corr_events (
  id bigint generated by default as identity primary key,
  org_id bigint not null default current_org_id(),
  corr_id bigint not null references public.correspondence(id) on delete cascade,
  action text not null,
  from_status text, to_status text,
  user_id bigint references public.users(id),
  to_user_id bigint references public.users(id),
  to_area_id bigint references public.corr_areas(id),
  note text,
  created_at timestamptz not null default now()
);
create index if not exists corr_events_corr_idx on public.corr_events (corr_id);
alter table public.corr_events enable row level security;

insert into public.corr_areas (org_id, name, prefix)
select o.id, a.name, a.prefix from public.plt_organizations o
cross join (values ('Gerencia / Dirección', 'GER'), ('Administrativo', 'ADM'), ('Talento Humano', 'TH'), ('IPS', 'IPS'), ('Socorro y Operaciones', 'SOC'), ('Educación', 'EDU'), ('Contabilidad', 'CON')) as a(name, prefix)
on conflict (org_id, prefix) do nothing;

insert into storage.buckets (id, name, public) values ('correspondencia', 'correspondencia', true) on conflict (id) do nothing;
