-- IIPS-028 · Aula virtual integrada (Jitsi) y plantillas de certificado.

-- 1) Clases virtuales: nueva plataforma "jitsi" (aula integrada, la sala la genera el sistema).
alter table public.edu_schedules drop constraint if exists edu_schedules_platform_check;
alter table public.edu_schedules add constraint edu_schedules_platform_check check (platform in ('meet', 'teams', 'zoom', 'otro', 'jitsi'));
alter table public.edu_sessions drop constraint if exists edu_sessions_platform_check;
alter table public.edu_sessions add constraint edu_sessions_platform_check check (platform in ('meet', 'teams', 'zoom', 'otro', 'jitsi'));
alter table public.edu_settings add column if not exists jitsi_domain text not null default 'meet.jit.si';

-- Registro de ingresos al aula virtual (quién entró y cuándo).
create table if not exists public.edu_virtual_joins (
  id bigint generated by default as identity primary key,
  org_id bigint not null default current_org_id(),
  session_id bigint not null references public.edu_sessions(id) on delete cascade,
  user_id bigint not null references public.users(id) on delete cascade,
  joined_at timestamptz not null default now()
);
create index if not exists edu_virtual_joins_session_idx on public.edu_virtual_joins (session_id);
alter table public.edu_virtual_joins enable row level security;

-- 2) Plantillas de certificado (cada cliente arma la suya).
create table if not exists public.edu_certificate_templates (
  id bigint generated by default as identity primary key,
  org_id bigint not null default current_org_id(),
  name text not null,
  is_default boolean not null default false,
  orientation text not null default 'landscape' check (orientation in ('landscape', 'portrait')),
  title_text text,
  intro_text text not null default 'Otorgado a',
  body_text text not null,
  closing_text text not null default 'Dado en {{ciudad}}, el {{fecha}}.',
  footer_text text,
  primary_color text not null default '#1F2A44',
  border_style text not null default 'doble' check (border_style in ('doble', 'simple', 'ninguno')),
  background_url text,
  show_logo boolean not null default true,
  signers jsonb not null default '[]',
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table public.edu_certificate_templates enable row level security;
alter table public.edu_programs add column if not exists certificate_template_id bigint references public.edu_certificate_templates(id) on delete set null;
