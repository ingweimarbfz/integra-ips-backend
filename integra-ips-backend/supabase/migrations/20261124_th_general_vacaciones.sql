-- IIPS-026 · Talento humano para personal no IPS (dependencias) y vacaciones según el tipo de contrato.

-- 1) Dependencias (administrativo, educación, conductores, contabilidad…). th_staff.dependency_id null = personal de IPS.
create table if not exists public.th_dependencies (
  id bigint generated by default as identity primary key,
  org_id bigint not null default current_org_id(),
  name text not null,
  sort_order integer not null default 0,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  unique (org_id, name)
);
alter table public.th_dependencies enable row level security;
alter table public.th_staff add column if not exists dependency_id bigint references public.th_dependencies(id) on delete set null;
create index if not exists th_staff_dependency_idx on public.th_staff (dependency_id);

insert into public.th_dependencies (org_id, name, sort_order)
select o.id, d.name, d.ord from public.plt_organizations o
cross join (values ('Administrativo', 1), ('Contabilidad', 2), ('Educación', 3), ('Conductores', 4), ('Socorro y operaciones', 5), ('Servicios generales', 6)) as d(name, ord)
on conflict (org_id, name) do nothing;

-- 2) Vacaciones disfrutadas o programadas (Código Sustantivo del Trabajo, art. 186: 15 días hábiles por año).
create table if not exists public.th_vacations (
  id bigint generated by default as identity primary key,
  org_id bigint not null default current_org_id(),
  staff_id bigint not null references public.th_staff(id) on delete cascade,
  start_date date not null,
  end_date date not null,
  business_days numeric not null check (business_days > 0),
  kind text not null default 'disfrute' check (kind in ('disfrute', 'compensadas')),
  notes text,
  created_by bigint references public.users(id),
  created_at timestamptz not null default now()
);
create index if not exists th_vacations_staff_idx on public.th_vacations (staff_id);
alter table public.th_vacations enable row level security;
